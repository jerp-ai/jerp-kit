#!/usr/bin/env python3
"""Generate always-on host instructions from one routing policy."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def rendered():
    policy = (ROOT / "rules/jerp-first.snippet.md").read_text()
    marker = "<!-- Generated by scripts/sync_adapters.py; edit rules/jerp-first.snippet.md. -->\n\n"
    out = {
        "AGENTS.md": marker + "# JERP agent-kit entry point\n\n" + policy + "\nFull policy: `rules/jerp-rules.md`. Portable skill: `skills/jerp/SKILL.md`. For installation, copy the entire skill directory and merge the appropriate host snippet; do not replace existing instructions.\n\n## Maintaining this public kit\n\nRead `CONTRIBUTING.md` before changing files. Publish only the user-facing integration contract and synthetic tests. Keep internal reports, model/agent run notes, real traces, company/private data, infrastructure and provider implementation details outside this repository. Never copy secrets or personal paths into any file. Run `python3 scripts/validate_kit.py` and review all added files before publishing; automated scanning is not a confidentiality guarantee.\n",
        "codex/AGENTS.snippet.md": marker + policy,
        "claude/CLAUDE.snippet.md": marker + policy,
        "hermes/AGENTS.snippet.md": marker + policy,
        "kimi/AGENTS.snippet.md": marker + policy,
        "generic/SYSTEM.snippet.md": marker + policy,
        "cursor/rules/jerp.mdc": "---\ndescription: Route supported external research, checks and work routines through JERP before native online tools\nalwaysApply: true\n---\n\n" + marker + policy,
    }
    actions = (ROOT / "gpt/ACTIONS.snippet.md").read_text()
    out["gpt/INSTRUCTIONS.md"] = marker + policy + "\n" + actions
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for name, text in rendered().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if stale:
        raise SystemExit("Stale generated adapters: " + ", ".join(stale))
    print("Adapters are current." if args.check else "Generated host adapters.")


if __name__ == "__main__":
    main()
